#!/usr/bin/env python3
"""Derive the constitution catalogue from rule files (lane 1: derived artifact).

Scans docs/constitution/**/rules/*.md, extracts rule metadata, and regenerates
registry/constitution-catalogue.json. The committed catalogue MUST equal the
derived output — this script proves it.

Usage:
  derive_catalogue.py <repo>              # regenerate in-memory, diff vs committed
  derive_catalogue.py <repo> --write      # overwrite the committed catalogue
"""
from __future__ import annotations

import json, re, sys
from pathlib import Path

repo = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
C = repo / "docs/constitution"
write = "--write" in sys.argv

RULE_FILE = re.compile(r"^#\s+([A-Z]{3,4}-\d{3})\b", re.M)
FIELD = re.compile(r"^\|\s*(Pack|Statement|References[^|]*|Evidence|Enforcement)\s*\|\s*([^|]*?)\s*\|", re.M)


def parse_rule(path: Path) -> dict | None:
    body = path.read_text(errors="replace")
    m = RULE_FILE.search(body)
    if not m: return None
    rid = m.group(1)
    pack = path.relative_to(C).parts[0] if len(path.relative_to(C).parts) > 1 else "root"
    fields = dict(FIELD.findall(body))
    return {
        "rule_id": rid,
        "pack": pack,
        "path": str(path.relative_to(repo)),
        "statement": fields.get("Statement", "")[:200],
        "refs": fields.get("References / enforcement", fields.get("References", ""))[:120],
    }


rules = []
for rf in sorted(C.rglob("rules/*.md")):
    r = parse_rule(rf)
    if r: rules.append(r)
# also scan absorbed rail files
for rf in sorted(C.rglob("rules/rail-*.md")):
    body = rf.read_text(errors="replace")
    for rid in re.findall(r"\b([A-Z]{2}-\d{3})\b", body):
        rules.append({"rule_id": rid, "pack": rf.relative_to(C).parts[0], "path": str(rf.relative_to(repo)), "statement": "", "refs": "rail"})

cat_path = C / "registry/constitution-catalogue.json"
if not cat_path.is_file():
    print(f"derive: no catalogue at {cat_path}", file=sys.stderr); sys.exit(2)

old = json.loads(cat_path.read_text())
new = {**old, "packs": rules, "derived": True, "note": "DERIVED — do not hand-edit. Regenerated by tools/ci/derive_catalogue.py or the engram-constitution skill's derive_catalogue.py."}
new_json = json.dumps(new, indent=2)

if write:
    cat_path.write_text(new_json)
    print(f"derive: wrote {len(rules)} rules to {cat_path.relative_to(repo)}")
    sys.exit(0)

committed = cat_path.read_text()
if committed != new_json:
    print(f"derive: DRIFT — committed catalogue does not match derivation ({len(rules)} rules). Run with --write to sync.", file=sys.stderr)
    sys.exit(1)
print(f"derive: OK ({len(rules)} rules, catalogue matches derivation)")
