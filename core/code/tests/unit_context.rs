//! Per-unit source categories and exact source-derived context ranges.
use engram_code::{TreeSitterChunker, analyze_code_unit, source_import_ranges};
use engram_domain::CodeSourceCategory;

fn category(source: &str, path: &str, symbol: &str) -> CodeSourceCategory {
    let parser = TreeSitterChunker::new().unwrap();
    let ext = path.rsplit('.').next().unwrap();
    let tree = parser.parse(source, ext).unwrap();
    let unit = parser
        .covered_chunks_with_tree(&tree, source, ext)
        .unwrap()
        .into_iter()
        .find(|p| {
            p.candidate
                .location
                .as_ref()
                .and_then(|l| l.anchor.as_ref())
                .is_some_and(|a| a.ends_with(symbol))
        })
        .unwrap();
    analyze_code_unit(source, path, &tree, unit.declaration_range).category
}

#[test]
fn inline_tests_in_production_paths_are_classified_per_unit_and_ancestry() {
    let rust = "pub fn save() {}\n#[cfg(test)]\nmod checks { #[test] fn validates() {} fn fixture() {} }\n";
    assert_eq!(
        category(rust, "src/storage.rs", "save"),
        CodeSourceCategory::Implementation
    );
    assert_eq!(
        category(rust, "src/storage.rs", "checks::validates"),
        CodeSourceCategory::Test
    );
    assert_eq!(
        category(rust, "src/storage.rs", "checks::fixture"),
        CodeSourceCategory::Test
    );
    let python = "import unittest\nclass Checks(unittest.TestCase):\n    def fixture(self):\n        return 1\n\ndef save():\n    return 1\n";
    assert_eq!(
        category(python, "src/storage.py", "Checks::fixture"),
        CodeSourceCategory::Test
    );
    assert_eq!(
        category(python, "src/storage.py", "save"),
        CodeSourceCategory::Implementation
    );
    let ts = "function save() {}\ndescribe('suite', () => { function scenario() {} });\n";
    assert_eq!(
        category(ts, "src/storage.ts", "save"),
        CodeSourceCategory::Implementation
    );
    assert_eq!(
        category(ts, "src/storage.ts", "scenario"),
        CodeSourceCategory::Test
    );
}

#[test]
fn generated_and_documentation_markers_stay_supporting_categories() {
    assert_eq!(
        category(
            "// Code generated by protoc. DO NOT EDIT.\npub fn render() {}",
            "src/model.rs",
            "render"
        ),
        CodeSourceCategory::Generated
    );
    assert_eq!(
        category("pub fn render() {}", "src/generated/model.rs", "render"),
        CodeSourceCategory::Generated
    );
    assert_eq!(
        category("pub fn render() {}", "docs/examples/sample.rs", "render"),
        CodeSourceCategory::Documentation
    );
    assert_eq!(
        category("pub fn render() {}", "tests/roundtrip.rs", "render"),
        CodeSourceCategory::Test
    );
}

#[test]
fn multiline_signature_and_imports_are_complete_exact_source_ranges() {
    let source = "use crate::storage::Database;\n\npub async fn get_user(\n    id: &str,\n) -> String {\n    query(id)\n}\n";
    let parser = TreeSitterChunker::new().unwrap();
    let tree = parser.parse(source, "rs").unwrap();
    let unit = parser
        .covered_chunks_with_tree(&tree, source, "rs")
        .unwrap()
        .into_iter()
        .find(|p| p.declaration_range.is_some())
        .unwrap();
    let analysis = analyze_code_unit(source, "src/users.rs", &tree, unit.declaration_range);
    let r = analysis.signature_range.unwrap();
    assert_eq!(
        &source[r.start as usize..r.end as usize],
        "pub async fn get_user(\n    id: &str,\n) -> String "
    );
    let imports = source_import_ranges(&tree);
    assert_eq!(imports.len(), 1);
    assert_eq!(
        &source[imports[0].start as usize..imports[0].end as usize],
        "use crate::storage::Database;"
    );
    assert_eq!(
        analyze_code_unit(source, "src/users.rs", &tree, None).category,
        CodeSourceCategory::Unknown
    );
}

#[test]
fn python_protobuf_and_grpc_generated_units_are_supporting() {
    for (header, path) in [
        (
            "# Generated by the protocol buffer compiler. DO NOT EDIT!",
            "src/service.py",
        ),
        (
            "# Generated by the gRPC Python protocol compiler plugin. DO NOT EDIT!",
            "src/service.py",
        ),
        ("", "src/service_pb2.py"),
        ("", "src/service_pb2_grpc.py"),
    ] {
        let source = format!("{header}\ndef create_stub():\n    return None\n");
        assert_eq!(
            category(&source, path, "create_stub"),
            CodeSourceCategory::Generated
        );
    }
    assert_eq!(
        category(
            "def save():\n    marker = 'generated by the protocol buffer compiler'\n    return marker\n",
            "src/storage.py",
            "save"
        ),
        CodeSourceCategory::Implementation
    );
}
