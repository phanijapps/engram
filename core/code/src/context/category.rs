//! Conservative per-unit category signals, including enclosing test syntax.
use super::node_text;
use engram_domain::CodeSourceCategory;
use tree_sitter::{Node, Tree};

pub(super) fn classify(
    source: &str,
    path: &str,
    tree: &Tree,
    node: Option<Node<'_>>,
) -> CodeSourceCategory {
    let lower = path.to_ascii_lowercase();
    let parts: Vec<_> = lower.split('/').collect();
    let name = parts.last().copied().unwrap_or("");
    let generated_path = parts
        .iter()
        .any(|p| matches!(*p, "generated" | "__generated__"))
        || name.contains(".generated.")
        || name.contains(".pb.")
        || name.ends_with("_pb2.py")
        || name.ends_with("_pb2_grpc.py");
    let mut cursor = tree.root_node().walk();
    let generated_header = tree
        .root_node()
        .named_children(&mut cursor)
        .take_while(|n| n.kind().contains("comment") || n.kind() == "shebang")
        .any(|n| {
            let text = node_text(source, n).to_ascii_lowercase();
            [
                "@generated",
                "<auto-generated",
                "code generated",
                "auto-generated",
                "automatically generated",
                "generated by the protocol buffer compiler",
                "generated by the grpc python protocol compiler plugin",
            ]
            .iter()
            .any(|marker| text.contains(marker))
        });
    if generated_path || generated_header {
        return CodeSourceCategory::Generated;
    }
    if parts.iter().any(|p| matches!(*p, "docs" | "documentation")) {
        return CodeSourceCategory::Documentation;
    }
    if parts
        .iter()
        .any(|p| matches!(*p, "test" | "tests" | "__tests__"))
        || name.starts_with("test_")
        || name.ends_with("_test.py")
        || name.ends_with("_test.go")
        || name.contains(".test.")
        || name.contains(".spec.")
        || matches!(name, "tests.rs" | "test.rs")
    {
        return CodeSourceCategory::Test;
    }
    let Some(mut current) = node else {
        return CodeSourceCategory::Unknown;
    };
    if current.has_error() {
        return CodeSourceCategory::Unknown;
    }
    let mut ambiguous_test = false;
    loop {
        let mut previous = current.prev_named_sibling();
        while let Some(sibling) = previous {
            if sibling.kind().contains("comment") {
                previous = sibling.prev_named_sibling();
                continue;
            }
            if !matches!(sibling.kind(), "attribute_item" | "inner_attribute_item") {
                break;
            }
            let text: String = node_text(source, sibling)
                .chars()
                .filter(|c| !c.is_whitespace())
                .collect();
            if text.contains("automatically_derived") {
                return CodeSourceCategory::Generated;
            }
            if text == "#[test]"
                || text.contains("::test]")
                || text.contains("::test(")
                || text.contains("cfg(test)")
                || text.contains("cfg(all(test,")
            {
                return CodeSourceCategory::Test;
            }
            ambiguous_test |= text.contains("cfg(") && text.contains("test");
            previous = sibling.prev_named_sibling();
        }
        if lower.ends_with(".py") {
            if current.kind() == "function_definition"
                && current
                    .child_by_field_name("name")
                    .is_some_and(|n| node_text(source, n).starts_with("test_"))
            {
                return CodeSourceCategory::Test;
            }
            if current.kind() == "class_definition" {
                let header = current
                    .child_by_field_name("body")
                    .map(|body| &source[current.start_byte()..body.start_byte()])
                    .unwrap_or("");
                if header.contains("TestCase")
                    || current
                        .child_by_field_name("name")
                        .is_some_and(|n| node_text(source, n).starts_with("Test"))
                {
                    return CodeSourceCategory::Test;
                }
            }
            if current.kind() == "decorator" || current.kind() == "decorated_definition" {
                let mut cursor = current.walk();
                if current
                    .named_children(&mut cursor)
                    .filter(|n| n.kind() == "decorator")
                    .any(|n| node_text(source, n).contains("pytest.fixture"))
                {
                    return CodeSourceCategory::Test;
                }
            }
        }
        if current.kind() == "call_expression"
            && let Some(function) = current.child_by_field_name("function")
        {
            let name = node_text(source, function);
            if ["test", "it", "describe"]
                .iter()
                .any(|base| name == *base || name.starts_with(&format!("{base}.")))
            {
                return CodeSourceCategory::Test;
            }
        }
        let Some(parent) = current.parent() else {
            break;
        };
        current = parent;
    }
    if ambiguous_test {
        CodeSourceCategory::Unknown
    } else {
        CodeSourceCategory::Implementation
    }
}
